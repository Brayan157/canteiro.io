CREATE TABLE employee (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    job_title VARCHAR(150),
    phone VARCHAR(40),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    user_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_employee_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_employee_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT uk_employee_user UNIQUE (user_id),
    CONSTRAINT ck_employee_name_not_blank CHECK (LENGTH(BTRIM(full_name)) > 0)
);

CREATE INDEX ix_employee_company_active ON employee (company_id, active);
CREATE UNIQUE INDEX uk_employee_id_company ON employee (id, company_id);

